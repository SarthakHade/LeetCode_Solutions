class Solution {
    public long countCommas(long n) {
        
        if (n < 1000)
            return 0;

        if (n <= 999999)
            return n - 999;

        if (n <= 999999999L)
            return (999999 - 999) + (n - 999999) * 2;

        if (n <= 999999999999L)
            return (999999 - 999)
                 + (999999999 - 999999) * 2
                 + (n - 999999999) * 3;

        if (n <= 999999999999999L)
            return (999999 - 999)
                 + (999999999 - 999999) * 2
                 + (999999999999L - 999999999) * 3
                 + (n - 999999999999L) * 4;

        return (999999 - 999)
             + (999999999 - 999999) * 2
             + (999999999999L - 999999999) * 3
             + (999999999999999L - 999999999999L) * 4
             + (n - 999999999999999L) * 5;
    }
}